// Walks the main flows in mock mode at 390×844 and saves screenshots to test-results/shots.
// Usage: node scripts/shots.mjs [baseUrl]
import { chromium } from '@playwright/test'
import { mkdirSync } from 'node:fs'

const BASE = process.argv[2] ?? 'http://localhost:5173'
const OUT = 'test-results/shots'
mkdirSync(OUT, { recursive: true })

const browser = await chromium.launch({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, permissions: ['camera'], isMobile: true, hasTouch: true })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` })
const wait = (ms) => page.waitForTimeout(ms)
const dev = async (label) => {
  await page.getByRole('button', { name: 'DEV', exact: true }).click()
  await page.getByRole('button', { name: label, exact: true }).click()
  await page.getByRole('button', { name: 'DEV', exact: true }).click()
}

try {
await page.goto(`${BASE}/?dev=1`)
await page.evaluate(() => { for (const k of Object.keys(localStorage)) if (k.startsWith('fs2.')) localStorage.removeItem(k) })
await page.goto(`${BASE}/?dev=1`)
await wait(2600)
await shot('01-cover')

await page.getByRole('button', { name: 'Open Passport' }).click()
await page.getByLabel('NRP', { exact: true }).fill('5025240028')
await page.getByRole('button', { name: 'Continue' }).click()
await page.getByLabel('Full name').fill('Peserta Demo')
await page.getByLabel('Department').selectOption('Informatics')
await page.getByLabel('Class of').selectOption('2024')
await page.getByLabel('4-digit PIN').fill('1234')
await page.getByLabel('Repeat PIN').fill('1234')
await shot('02-register')
await page.getByRole('button', { name: 'Create passport' }).click()

await page.waitForURL('**/photo')
await wait(1500)
await shot('03-foto')
await page.getByRole('button', { name: 'Take photo' }).click()
await wait(1000)
await shot('03b-foto-polaroid')
await page.getByRole('button', { name: 'Use this photo' }).click()
await wait(900)
await shot('03c-foto-fly')

await page.waitForURL('**/onboarding')
await wait(2600)
await shot('04a-onboarding-draw')
await wait(1800)
await shot('04b-onboarding-zoom')
await wait(1800)
await shot('04c-onboarding-card')
await page.getByRole('button', { name: 'Start' }).click()

await page.waitForURL('**/map')
await wait(800)
await shot('05-peta')
await page.getByRole('tab', { name: 'Whole building' }).click()
await wait(700)
await shot('06-peta-gedung')
await page.getByRole('tab', { name: 'Lounge' }).click()
await wait(600)
await page.getByRole('button', { name: /Taiwan booth/ }).click()
await wait(900)
await shot('07-booth-sheet')
await page.getByRole('button', { name: 'Close', exact: true }).click()
await wait(400)

await page.getByRole('button', { name: 'QR', exact: true }).click()
await wait(800)
await shot('08-qr')
await dev('Stamp B2')
await page.waitForURL('**/stamp/B2', { timeout: 6000 })
await wait(450)
await shot('09a-cap-mid')
await wait(1400)
await shot('09b-cap')
await page.getByRole('button', { name: 'Write now' }).click()
await page.waitForURL('**/visa/B2')
await page.getByLabel(/Point 1/).fill('Program magang riset di Taiwan bisa jadi jalan pertama ke luar negeri.')
await page.getByLabel(/Point 2/).fill('Hal baru')
await wait(2200)
await shot('10-visa')
await page.getByRole('button', { name: 'Done' }).click()
await page.waitForURL('**/passport')
await wait(600)
await shot('11-paspor')

for (const b of ['Stamp B1', 'Stamp B3', 'Stamp B4']) {
  await dev(b)
  await page.waitForURL('**/stamp/**', { timeout: 6000 })
  await wait(1600)
  await page.getByRole('button', { name: /Next booth|Back to map/ }).click()
  await page.waitForURL('**/map')
}
await wait(1200)
await shot('12-peta-4of4')
await dev('Auto-fill notes')
await page.goto(`${BASE}/exit`)
await wait(600)
await page.getByRole('radio').nth(4).click()
await shot('13-keluar-partial')
await page.getByRole('radio').nth(8).click()
await wait(400)
await page.getByRole('button', { name: 'Submit' }).click()
await wait(1300)
await shot('14-kirim-anim')
await page.waitForURL('**/status', { timeout: 6000 })
await wait(700)
await shot('15-status')

// staff
await page.goto(`${BASE}/staff/korea`)
await page.getByLabel('Booth PIN').fill('1111')
await page.getByRole('button', { name: 'Sign in' }).click()
await wait(500)
await dev('+ 12 dummy participants')
await page.getByRole('button', { name: 'DEV', exact: true }).click()
await page.getByRole('checkbox', { name: /Simulation mode/ }).check()
await page.getByRole('button', { name: 'DEV', exact: true }).click()
for (let i = 0; i < 3; i++) {
  await page.getByRole('button', { name: /simulate a participant QR scan/ }).click()
  await wait(350)
}
await wait(400)
await shot('16-scanner')
await page.getByRole('button', { name: /Confirm all/ }).click()
await wait(900)
await shot('17-scanner-confirmed')
await page.getByRole('tab', { name: /History/ }).click()
await wait(500)
await shot('18-riwayat')

// admin
await page.setViewportSize({ width: 1280, height: 800 })
await page.goto(`${BASE}/admin`)
await page.getByLabel('Password').fill('fs2admin')
await page.getByRole('button', { name: 'Sign in' }).click()
await wait(800)
await shot('19-admin-ringkasan')
await page.getByRole('link', { name: /Submissions/ }).click()
await wait(500)
await page.getByRole('button', { name: /Peserta Demo/ }).click()
await wait(600)
await shot('20-admin-pengajuan')
await page.getByRole('link', { name: 'Booths & content' }).click()
await wait(700)
await shot('21-admin-konten')
} catch (e) {
  console.log('FAILED at', page.url(), String(e).split('\n')[0])
  await shot('zz-failure')
}

console.log(errors.length ? `ERRORS:\n${errors.join('\n')}` : 'no console errors')
await browser.close()
