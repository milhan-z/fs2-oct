// Generates supabase/seed.sql (content only — no credentials) from data/seed.json.
import { readFileSync, writeFileSync } from 'node:fs'

const seed = JSON.parse(readFileSync('data/seed.json', 'utf8'))
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const j = (v) => `${q(JSON.stringify(v))}::jsonb`
const stamp = (p) => (p ? `/assets/stamps/${p.split('/').pop().replace(/\.png$/, '')}.webp` : null)

const out = ['-- Generated by scripts/gen-seed-sql.mjs from data/seed.json. Safe to re-run (upserts).', 'begin;']
seed.booths.forEach((b, i) => {
  out.push(
    `insert into public.booths (id, slug, nama, region, stamp_url, x, y, placeholder_pos, sort) values (${[b.id, b.slug, b.nama, b.region, stamp(b.stamp), b.titik.x, b.titik.y, b.placeholder_posisi, i + 1].map(q).join(', ')})
  on conflict (id) do update set slug = excluded.slug, nama = excluded.nama, region = excluded.region, stamp_url = excluded.stamp_url, x = excluded.x, y = excluded.y, placeholder_pos = excluded.placeholder_pos, sort = excluded.sort;`,
  )
  b.pemateri.forEach((p, k) => {
    out.push(
      `insert into public.speakers (id, booth_id, nama, universitas, program, foto_url, cerita, placeholder, sort) values (${[`${b.id}-s${k + 1}`, b.id, p.nama, p.universitas, p.program, p.foto, p.cerita, p.placeholder, k + 1].map(q).join(', ')})
  on conflict (id) do update set nama = excluded.nama, universitas = excluded.universitas, program = excluded.program, foto_url = excluded.foto_url, cerita = excluded.cerita, placeholder = excluded.placeholder;`,
    )
  })
})
seed.fasilitas.forEach((f, i) => {
  out.push(
    `insert into public.facilities (id, jenis, label, x, y, placeholder, catatan) values (${[`F${i + 1}`, f.jenis, f.label, f.titik?.x ?? null, f.titik?.y ?? null, f.placeholder, f.catatan].map(q).join(', ')})
  on conflict (id) do update set jenis = excluded.jenis, label = excluded.label, x = excluded.x, y = excluded.y, placeholder = excluded.placeholder, catatan = excluded.catatan;`,
  )
})
seed.feedback.forEach((f, i) => {
  out.push(
    `insert into public.feedback_questions (id, teks, tipe, wajib, sort, section, label_low, label_high) values (${[f.id, f.teks, f.tipe, f.wajib, i + 1, f.section ?? null, f.labelLow ?? null, f.labelHigh ?? null].map(q).join(', ')})
  on conflict (id) do update set teks = excluded.teks, tipe = excluded.tipe, wajib = excluded.wajib, sort = excluded.sort, section = excluded.section, label_low = excluded.label_low, label_high = excluded.label_high;`,
  )
})
const e = seed.event
const settings = {
  event: { nama: e.nama, tagline: e.tagline, tanggal: e.tanggal, jam_acara: e.jam_acara, tempat: e.tempat, kontak_bantuan: e.kontak_bantuan, rundown: e.rundown },
  rooms: seed.ruang_label,
  rules: seed.aturan,
  session_start: e.sesi_booth.mulai,
  session_end: e.sesi_booth.selesai,
  deadline: e.batas_kirim,
}
for (const [k, v] of Object.entries(settings)) out.push(`insert into public.settings (key, value) values (${q(k)}, ${j(v)}) on conflict (key) do update set value = excluded.value;`)
out.push(`insert into public.settings (key, value) values ('simulation_mode', 'false'::jsonb) on conflict (key) do nothing;`)
out.push('commit;', '')
writeFileSync('supabase/seed.sql', out.join('\n'))
console.log('wrote supabase/seed.sql')
